from ultralytics import YOLO

if __name__ == '__main__':
    # 1. 加载预训练模型
    model = YOLO('best800.pt', task='detect')
    # 2. 启动训练
    results = model.train(
        # ---------------------- 基础核心配置 ----------------------
        data='pic.yaml',  # 数据集配置文件
        epochs=100,          # 训练总轮次
        imgsz=(480, 800),    # 输入图像尺寸：格式为 (高度, 宽度)，对应高480、宽800
        rect=True,           # 开启矩形训练，适配非正方形比例，避免图像拉伸变形

        # ---------------------- 数据加载配置 ----------------------
        workers=4,           # 数据加载线程数，可根据CPU核心数调整
        batch=4,             # 批次大小，显存不足可调小为2
        cache='ram',         # 小数据集、内存充足：cache='ram'

        # ---------------------- 数据增强（适配小球检测） ----------------------
        # 颜色增强：适配不同光照、不同颜色的小球
        hsv_h=0.02,          # 色相微调，避免小球颜色过度偏移
        hsv_s=0.5,           # 饱和度增强，突出小球颜色特征
        hsv_v=0.5,           # 亮度增强，适应明暗不同的拍摄环境
        # 几何增强：小球为对称物体，可适度做几何变换扩充数据
        degrees=2.0,         # 随机旋转角度范围
        translate=0.2,       # 随机平移幅度
        scale=0.2,           # 随机缩放幅度，适配远近不同大小的小球
        fliplr=0.2,          # 水平翻转概率

        # ---------------------- 优化器参数 ----------------------
        optimizer='AdamW',   # 优化器类型，小数据集下收敛速度优于SGD
        lr0=0.001,           # 初始学习率
        lrf=0.01,            # 最终学习率因子 = 初始学习率 * lrf
        momentum=0.937,
        weight_decay=0.0005, # 权重衰减，抑制过拟合
        warmup_epochs=5.0,   # 学习率热身轮次
        warmup_momentum=0.8,

        # ---------------------- 损失函数权重 ----------------------
        box=7.5,             # 边界框定位损失权重，小球检测定位精度很重要
        cls=0.5,             # 分类损失权重，单类别场景可适当降低
        dfl=1.5,             # 分布焦点损失权重
        label_smoothing=0.0, # 标签平滑，类别少时可保持0

        # ---------------------- 训练控制与保存 ----------------------
        patience=50,         # 早停耐心值：连续30轮验证集无提升则自动终止训练
        save=True,           # 自动保存最佳模型和最后一轮模型
        save_period=-1,      # 不保存中间轮次检查点，节省磁盘空间
        val=True,            # 每轮训练后执行验证集评估

        # ---------------------- 输出路径与可视化 ----------------------
        project=r'runs\train',
        name='ball',  # 本次实验文件夹名称，方便区分不同训练
        exist_ok=False,      # 不覆盖已有同名实验，自动新建序号文件夹
        plots=True,          # 生成训练曲线、混淆矩阵、PR曲线等可视化图表
        verbose=True         # 打印详细训练日志
    )
